/* ---------------- AIBadge ---------------- */
export function AIBadge({ className, label = "AI", title }: { className?: string; label?: string; title?: string }) {
  return (
    <Badge tone="ai" className={cn("gap-0.5", className)} title={title ?? "Generated by the AI agent"}>
      <Sparkles aria-hidden />
      <span>{label}</span>
    </Badge>
  );
}

